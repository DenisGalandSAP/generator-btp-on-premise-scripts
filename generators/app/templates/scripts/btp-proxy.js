#!/usr/bin/env node
/*
 * Local proxy to reach an on-premise backend through a BTP destination.
 *
 * - Reads destination + connectivity credentials from a CF app's environment
 *   (in memory, via `cf curl`, nothing written to disk).
 * - Opens `cf ssh -L` to the connectivity proxy (only reachable from inside CF).
 * - Listens on http://127.0.0.1:<PORT> (this machine only) and forwards every request through the
 *   tunnel to the destination's URL, adding the connectivity JWT, the Cloud
 *   Connector location id and sap-client.
 *
 * Usage: node scripts/btp-proxy.js [--profile <env>] [--destination <name>] [--port <n>] [--tunnel-port <n>]
 * Env (.env.<profile> in the project root, generated by @scodigis/generator-btp-on-premise-scripts, see btp-env.js):
 *        BTP_APP                    CF app bound to the destination + connectivity services (ssh enabled)
 *        BTP_CF_API / BTP_CF_ORG / BTP_CF_SPACE  where BTP_APP lives (cf is retargeted to it)
 *        BTP_DESTINATION            destination (overridden by --destination)
 *        BTP_PROXY_PORT (5050), BTP_TUNNEL_PORT (20003)   overridden by --port / --tunnel-port
 *        BTP_PROXY_USER / BTP_PROXY_PWD (optional) - Basic auth if the destination has no auth and the
 *        request has none (USR / SAP_PWD are the deploy credentials, not used here)
 */
const http = require("http");
const net = require("net");
const { execFileSync, spawn } = require("child_process");
const { loadProfile, ensureCfTarget, cf, cfCommand } = require("./btp-env");

const arg = (name) => {
	const i = process.argv.indexOf(`--${name}`);
	return i > 0 ? process.argv[i + 1] : undefined;
};
let PROFILE;
try {
	PROFILE = loadProfile(arg("profile"));
} catch (e) {
	console.error(`[btp-proxy] ${e.message}`);
	process.exit(1);
}
const APP = process.env.BTP_APP;
const DESTINATION = arg("destination") || process.env.BTP_DESTINATION;
const PORT = Number(arg("port") || process.env.BTP_PROXY_PORT || 5050);
const TUNNEL_PORT = Number(arg("tunnel-port") || process.env.BTP_TUNNEL_PORT || 20003);
if (!APP || !DESTINATION) {
	console.error(`[btp-proxy] BTP_APP and BTP_DESTINATION must be set (${PROFILE ? `.env.${PROFILE}` : ".env"}) - run the 'BTP On-Premise Access' generator again`);
	process.exit(1);
}

async function clientCredentialsToken(creds) {
	const res = await fetch(`${creds.url}/oauth/token`, {
		method: "POST",
		headers: { "content-type": "application/x-www-form-urlencoded" },
		body: new URLSearchParams({
			grant_type: "client_credentials",
			client_id: creds.clientid,
			client_secret: creds.clientsecret
		})
	});
	if (!res.ok) throw new Error(`Token request failed: ${res.status} ${await res.text()}`);
	const json = await res.json();
	return { token: json.access_token, expiresAt: Date.now() + (json.expires_in - 60) * 1000 };
}

// cf ssh binds the local port only once the ssh session is up - poll until it accepts connections
async function waitForPort(port, timeoutMs) {
	const deadline = Date.now() + timeoutMs;
	for (;;) {
		const open = await new Promise((resolve) => {
			const socket = net.connect({ host: "127.0.0.1", port }, () => { socket.destroy(); resolve(true); });
			socket.on("error", () => resolve(false));
		});
		if (open) return;
		if (Date.now() > deadline) throw new Error(`ssh tunnel not ready on 127.0.0.1:${port} after ${timeoutMs / 1000}s`);
		await new Promise((r) => setTimeout(r, 500));
	}
}

function cachedToken(creds) {
	let cache;
	return async () => {
		if (!cache || Date.now() > cache.expiresAt) cache = await clientCredentialsToken(creds);
		return cache.token;
	};
}

async function main() {
	// cf app / cf ssh work on the targeted space; started by btp.js it is already right,
	// on its own a needed cf login runs in this terminal
	ensureCfTarget({ interactive: true, log: (msg) => console.log(`[btp-proxy] ${msg}`) });
	console.log(`[btp-proxy] reading service bindings of '${APP}'...`);
	const guid = cf("app", APP, "--guid");
	const env = JSON.parse(cf("curl", `/v3/apps/${guid}/env`));
	const vcap = env.system_env_json && env.system_env_json.VCAP_SERVICES;
	if (!vcap || !vcap.destination || !vcap.connectivity) {
		throw new Error(`App '${APP}' must be bound to a destination and a connectivity service (are you logged in with 'cf login'?)`);
	}
	const destCreds = vcap.destination[0].credentials;
	const connCreds = vcap.connectivity[0].credentials;
	const destToken = cachedToken(destCreds);
	const connToken = cachedToken(connCreds);

	// "find destination" also returns ready-to-use auth headers (authTokens), e.g. for BasicAuthentication
	let destCache;
	const findDestination = async () => {
		if (destCache && Date.now() < destCache.expiresAt) return destCache;
		const res = await fetch(`${destCreds.uri}/destination-configuration/v1/destinations/${DESTINATION}`, {
			headers: { authorization: `Bearer ${await destToken()}` }
		});
		if (!res.ok) throw new Error(`Destination '${DESTINATION}' lookup failed: ${res.status} ${await res.text()}`);
		const json = await res.json();
		const authToken = (json.authTokens || []).find((t) => !t.error);
		destCache = {
			config: json.destinationConfiguration,
			authHeader: authToken && (authToken.http_header ? authToken.http_header.value : `${authToken.type} ${authToken.value}`),
			expiresAt: Date.now() + 5 * 60 * 1000
		};
		return destCache;
	};
	const dest = (await findDestination()).config;
	if (dest.ProxyType !== "OnPremise") throw new Error(`Destination '${DESTINATION}' is not OnPremise`);
	const target = new URL(dest.URL);
	console.log(`[btp-proxy] destination ${DESTINATION} -> ${dest.URL} (client ${dest["sap-client"] || "-"}, location ${dest.CloudConnectorLocationId || "-"}, auth ${dest.Authentication})`);

	const proxyHost = connCreds.onpremise_proxy_host;
	const proxyPort = connCreds.onpremise_proxy_http_port || connCreds.onpremise_proxy_port;
	console.log(`[btp-proxy] opening ssh tunnel 127.0.0.1:${TUNNEL_PORT} -> ${proxyHost}:${proxyPort} via '${APP}'...`);
	const tunnel = spawn(...cfCommand(["ssh", APP, "-N", "-L", `127.0.0.1:${TUNNEL_PORT}:${proxyHost}:${proxyPort}`], { stdio: "inherit" }));
	tunnel.on("exit", (code) => {
		console.error(`[btp-proxy] ssh tunnel exited (${code})`);
		process.exit(1);
	});
	const stop = (code = 0) => {
		tunnel.removeAllListeners("exit");
		// on Windows cf is often a shim (e.g. chocolatey) - kill the whole tree so no tunnel is left behind
		if (process.platform === "win32") {
			try { execFileSync("taskkill", ["/pid", String(tunnel.pid), "/T", "/F"], { stdio: "ignore" }); } catch (e) { /* already gone */ }
		} else {
			tunnel.kill();
		}
		process.exit(code);
	};
	process.on("SIGINT", () => stop());
	process.on("SIGTERM", () => stop());

	try {
		await waitForPort(TUNNEL_PORT, 60000);
	} catch (err) {
		console.error(`[btp-proxy] ${err.message}`);
		stop(1);
	}
	console.log(`[btp-proxy] ssh tunnel ready`);

	const basicAuth = process.env.BTP_PROXY_USER && process.env.BTP_PROXY_PWD
		? "Basic " + Buffer.from(`${process.env.BTP_PROXY_USER}:${process.env.BTP_PROXY_PWD}`).toString("base64")
		: undefined;

	// Through a Cloud Connector, some ABAP systems reject a Basic logon that arrives without the
	// sap-ssolist / sap-usercontext cookies it hands out on a 401 (no failed-logon count either).
	// Browsers get them from the challenge round trip; tools sending credentials up front
	// (fiori deploy) do not. So fetch them once per client, unauthenticated, and add them.
	const PRIME_COOKIES = ["sap-ssolist", "sap-usercontext"];
	const primed = new Map();
	const primeCookies = async (url, baseHeaders) => {
		const client = url.searchParams.get("sap-client") || "";
		const cached = primed.get(client);
		if (cached && Date.now() < cached.expiresAt) return cached.cookies;
		const primeHeaders = { ...baseHeaders };
		delete primeHeaders.authorization;
		delete primeHeaders.cookie;
		delete primeHeaders["content-type"];
		delete primeHeaders["content-length"];
		delete primeHeaders["transfer-encoding"];
		const cookies = await new Promise((resolve, reject) => {
			http.request({ host: "127.0.0.1", port: TUNNEL_PORT, method: "GET", path: url.href, headers: primeHeaders }, (up) => {
				up.resume();
				resolve((up.headers["set-cookie"] || []).map((c) => c.split(";")[0]).filter((c) => PRIME_COOKIES.includes(c.split("=")[0])));
			}).on("error", reject).end();
		});
		primed.set(client, { cookies, expiresAt: Date.now() + 10 * 60 * 1000 });
		return cookies;
	};

	http.createServer(async (req, res) => {
		// used by scripts/btp.js to tell a running btp-proxy from anything else on the port
		if (req.url === "/__btp-proxy/health") {
			res.writeHead(200, { "content-type": "application/json" });
			res.end(JSON.stringify({ profile: PROFILE, app: APP, destination: DESTINATION, port: PORT, tunnelPort: TUNNEL_PORT }));
			return;
		}
		try {
			const url = new URL(req.url, target);
			if (dest["sap-client"] && !url.searchParams.has("sap-client")) {
				url.searchParams.set("sap-client", dest["sap-client"]);
			}
			const headers = { ...req.headers, host: target.host };
			delete headers.connection;
			headers["proxy-authorization"] = `Bearer ${await connToken()}`;
			if (dest.CloudConnectorLocationId) headers["sap-connectivity-scc-location_id"] = dest.CloudConnectorLocationId;
			const { authHeader } = await findDestination();
			if (authHeader) headers.authorization = authHeader;
			else if (basicAuth && !headers.authorization) headers.authorization = basicAuth;
			if (/^Basic /i.test(headers.authorization || "") && !/(^|;\s*)sap-ssolist=/.test(headers.cookie || "")) {
				const extra = await primeCookies(url, headers);
				const existing = (headers.cookie || "").split(";").map((c) => c.trim()).filter(Boolean);
				const names = new Set(existing.map((c) => c.split("=")[0]));
				headers.cookie = existing.concat(extra.filter((c) => !names.has(c.split("=")[0]))).join("; ");
			}
			if (process.env.BTP_PROXY_DEBUG) {
				const [scheme, value] = (headers.authorization || "").split(" ");
				const user = scheme === "Basic" ? Buffer.from(value, "base64").toString("utf8").split(":")[0] : undefined;
				const cookieNames = (headers.cookie || "").split(";").map((c) => c.split("=")[0].trim()).filter(Boolean);
				console.log(`[btp-proxy] ${req.method} ${url.href} auth=${scheme || "none"}${user ? ` user=${user}` : ""} cookies=${cookieNames.join(",") || "none"} headers=${Object.keys(headers).join(",")}`);
			}

			// Plain HTTP request to the connectivity proxy with an absolute URL (HTTP proxy semantics)
			const upstream = http.request({
				host: "127.0.0.1",
				port: TUNNEL_PORT,
				method: req.method,
				path: url.href,
				headers
			}, (up) => {
				if (process.env.BTP_PROXY_DEBUG) {
					const h = up.headers;
					const setCookies = (h["set-cookie"] || []).map((c) => c.split("=")[0]).join(",");
					console.log(`[btp-proxy]   <- ${up.statusCode} ${req.method} ${url.pathname} sap-system=${h["sap-system"] || "-"} www-authenticate=${h["www-authenticate"] || "-"} set-cookie=${setCookies || "-"}`);
				}
				res.writeHead(up.statusCode, up.headers);
				up.pipe(res);
			});
			upstream.on("error", (err) => {
				console.error(`[btp-proxy] ${req.method} ${req.url}: ${err.message}`);
				if (!res.headersSent) res.writeHead(502);
				res.end(`btp-proxy: ${err.message}`);
			});
			req.pipe(upstream);
		} catch (err) {
			console.error(`[btp-proxy] ${err.message}`);
			res.writeHead(500);
			res.end(`btp-proxy: ${err.message}`);
		}
	}).listen(PORT, "127.0.0.1", () => console.log(`[btp-proxy] listening on http://127.0.0.1:${PORT}`));
}

main().catch((err) => {
	console.error(`[btp-proxy] ${err.message}`);
	process.exit(1);
});
